"""The public-repository gate: what it must flag, and what it must let through."""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / ".github" / "scripts" / "check_public_hygiene.py"
spec = importlib.util.spec_from_file_location("check_public_hygiene", SCRIPT)
hygiene = importlib.util.module_from_spec(spec)
spec.loader.exec_module(hygiene)


@pytest.mark.parametrize("text,rule", [
    ("token = 'phare_pat_Qm3xT9vL2pZ8wR4sK7nH1jF6dB0yC5aE'", "Phare access token"),
    ("AWS_ACCESS_KEY_ID=AKIAIOSFODNN7EXAMPLE", "AWS access key"),
    ("-----BEGIN RSA PRIVATE KEY-----", "private key block"),
    ("arn:aws:lambda:us-east-1:123456789012:function:x", "AWS account id or ARN"),
    ("BASE = 'https://dev.api.pharelabs.com/protect'", "non-production Phare host"),
    ("https://sandbox.iot.pharelabs.com", "non-production Phare host"),
    ("owner: jane.doe@pharelabs.com", "company e-mail address"),
    ("JANE.DOE@PHARELABS.COM", "company e-mail address"),
    ("ops@mail.pharelabs.com", "company e-mail address"),
    ("jane.security@pharelabs.com", "company e-mail address"),
    ("jane-support@pharelabs.com", "company e-mail address"),
    ("https://abc123defg.execute-api.eu-west-2.amazonaws.com/prod", "API Gateway endpoint"),
    ("call +44 7700 900123", "phone number"),
    ("+1 415 555 0100", "phone number"),
    ("(+34) 612-345-678", "phone number"),
    ("user auth0|0123456789abcdef01234567", "Auth0 user id"),
    ("auth0|0123456789ABCDEF01234567", "Auth0 user id"),
    ("Co-Authored-By: Claude Fable 5.1 <noreply@anthropic.com>", "AI attribution"),
    ("Co-authored-by: Cursor <cursoragent@cursor.com>", "AI attribution"),
    ("Co-authored-by: Codex <codex@openai.com>", "AI attribution"),
    ("Co-authored-by: Gemini", "AI attribution"),
    ("co-authored-by: Devin AI <devin@example.com>", "AI attribution"),
    ("Assisted-by: Claude", "AI attribution"),
    ("Generated by GitHub Copilot", "AI attribution"),
    ("🤖 Generated with [Claude Code](https://claude.com/claude-code)", "AI attribution"),
    ("Made with Cursor", "AI attribution"),
])
def test_must_flag(text, rule):
    assert rule in hygiene.line_problems(text)


@pytest.mark.parametrize("text", [
    'TOKEN = "phare_pat_testtokentesttokentesttokentesttoken00"',
    "Report issues to security@pharelabs.com or support@pharelabs.com.",
    "Brings your [Phare](https://pharelabs.com) sensors into Home Assistant",
    "https://api.pharelabs.com/protect",
    '"device_id": "351103920000001"',
    '"ts": "2026-10-02T09:50:00+02:00"',
    "address_lat: 51.5074, address_lng: -0.1278",
    "codeowners: @esrabrahmii",
    "Reviewed the claudication study; the authors thank Claudette.",
    "python -m pytest -q",
    "version 2026.2.3",
])
def test_must_pass(text):
    assert hygiene.line_problems(text) == []


def test_repository_is_clean():
    assert hygiene.scan_files() == []


def test_this_file_and_the_script_are_exempt_from_the_file_scan():
    assert "tests/test_public_hygiene.py" in hygiene.EXEMPT_FILES
    assert hygiene.SELF in hygiene.EXEMPT_FILES
